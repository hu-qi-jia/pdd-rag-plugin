/**
 * 聊天页推荐面板的字型规范(2026-09-17 第五十轮用户"规范一下字号和权重")。
 *
 * 面板此前是**五档字号(10.5 / 11.5 / 12.5 / 13.5 / 15)+ 三档字重(400 / 500 / 600)**
 * 各处零散取用:折叠数与脚注 10.5、计数 12.5、徽标 500 —— 每一处单看都说得过去,
 * 合起来就是"没有规范"。现收敛为:
 *
 *   **三档字号**(等差 2px):标题 15 > 内容 13.5 > 辅助 11.5
 *   **两档字重**:regular 400 / semibold 600(500 在面板里退役 ——
 *   "比正文重一点又不到半粗"是最没有信息量的一档,该强调就 600,不强调就 400)
 *
 * 落位规则(铁律:面板里任何文字必须落在下表之一,禁止 `fontSize.caption + 0.5` 这类临时值):
 *  - `title`   —— 面板名「推荐回复」;
 *  - `content` —— **面板唯一主层**:候选正文、整合生成结果,以及整合行主行的动作名
 *                 (动作名与内容**同档字号**,靠字重 600 + 知识库绿区分,不再另开一档);
 *  - `meta`    —— 全部辅助文字:问题引子、来源、计数、折叠数、动作说明、脚注、键帽。
 *                同一个面板里"次要信息"只有一种字号,不按重要程度再分小档。
 */
export const panelType = {
  /** 面板名(15 / 600) */
  title: { size: fontSize.heading, weight: fontWeight.semibold },
  /** 内容层:候选正文、生成结果(13.5 / 400)—— 面板唯一主层 */
  content: { size: fontSize.title, weight: fontWeight.regular },
  /** 动作层:整合行动作名、类别徽标(13.5 或 11.5 + 600,与所在行的内容同档) */
  action: { size: fontSize.title, weight: fontWeight.semibold },
  /** 辅助层:引子、来源、计数、折叠数、说明、脚注(11.5 / 400) */
  meta: { size: fontSize.secondary, weight: fontWeight.regular },
} as const

