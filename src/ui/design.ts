/**
 * 设计规范(Design Tokens)— 本扩展唯一视觉真源
 *
 * v3.0 设计语言:**复古极简主义(Retro Minimalism)+ 极客工具风(Geek UI)**。
 *
 * 参照物不是 Figma / Apple,而是**台面仪器与早期终端**:BIOS 设置屏、Norton Commander
 * 的双线框、Teenage Engineering 的硬件面板、终端里的 `ls -l` 输出。四条口径:
 *
 *  1. **黑白灰,几乎无彩色** —— 层级只由「墨的浓度」表达:纯黑文本 / 中灰 / 浅灰,
 *     加上两枚印刷油墨级的语义色(暗琥珀、暗墨绿)作为**功能信号**,不做装饰。
 *  2. **等宽字** —— 拉丁与数字走终端等宽字,CJK 落到雅黑(见 fontFamily)。
 *     等宽字自带栅格感,且让数值天然对齐;禁止负字距(那是比例字的排版手法)。
 *  3. **硬朗几何** —— **全线直角**:radius 令牌一律 0,圆角只留一个开关(改这一处即可回到圆角)。
 *     没有阴影、没有模糊、没有渐变材质;分隔靠 **1px 实线**,且线的**粗细/深浅本身编码层级**
 *     (borderStrong 结构线 > border 分区线 > borderLight 行线)。
 *  4. **高信息密度** —— 控件 24/26px,行距 12px 栅格,分区不再套卡片盒子(改为一根横线 + 一个标签),
 *     同样的窗口能装下更多参数。
 *
 * 任何页面/组件不得硬编码字号、圆角、间距、颜色,一律引用本文件与 theme.ts。
 * 配色令牌见 theme.ts(ThemeTokens),本文件负责几何与字型。
 */

// ── 字体栈 — 终端等宽优先;拉丁/数字走等宽,CJK 落到雅黑 ──────────────────────
/**
 * 顺序即口径:前面的字体没有该字形时浏览器**逐字**回退,于是
 * `ui-monospace / Cascadia / Consolas` 接管拉丁与数字(终端感、数值天然对齐),
 * 汉字落回 `Microsoft YaHei`(等宽字体普遍不含 CJK,这不是降级而是分工)。
 * 不联网加载字体。
 */
export const fontFamily =
  'ui-monospace, "SF Mono", "Cascadia Code", "Cascadia Mono", "JetBrains Mono", Consolas, monospace, "Microsoft YaHei"'

