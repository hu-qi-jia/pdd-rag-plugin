// ── 圆角(px)— 四档,每种用途一档,不许混用 ─────────────────────────────────
/**
 * v4.0 → v5.0 的关键变化:**列表重新有了圆角**。
 *
 * v4.0 把行做成通铺(理由:整页同一类条目,拆成块就成了碎片),v5.0 按第六十七轮
 * 设计稿改回**每行一张卡**。于是圆角从三档变四档,并且**卡档要比控件档大** ——
 * 大面积的容器配小圆角会显得"没倒角",小控件配大圆角会显得"太软"。
 *
 * 档位关系(由大到小):浮层 20 > 卡片 16 > 控件 14。相邻档差 2–5px,
 * 保证"哪个裹着哪个"一眼能读出来,又不至于像三种不同的语言。
 *
 * ── 圆角规范(2026-10-24 收口,`tests/unit/ui/radius-spec.test.ts` 机检)────────
 *  ① **四档是唯一来源**:代码里只许出现这四个令牌。`border-radius` 写数字、
 *     `borderRadius: 13` 这种内联数字,单测会直接判失败(唯二例外:正圆 50%、
 *     直角 0)。来源标签的 4px 是 `overlay-css#BADGE_RADIUS` —— 它是标签不是控件。
 *  ② **按语义选档,不按尺寸选**:能被点的(按钮/输入框/chip)= control;
 *     装内容的卡 = card;浮在别的内容之上的面 = panel;两端全圆 = pill。
 *  ③ **相邻档差 2–5px**。差 1px 读不出层级,差 6px 以上就读成两套语言了。
 *  ④ **同心**:圆角容器里有圆角子元素、且内缩 ≥ 4px 时,子圆角 = 父圆角 − 内缩,
 *     两条弧才平行;内缩 ≤ 2px 时保持同档(肉眼看不出,新增一档反而破坏纪律)。
 *  ⑤ **卡片 ≤ 列表内缩**(`listGap.inset`),否则转角贴着容器边缘会被读成"切平";
 *     而列表内缩又必须等于页面左右内边距(`pageGap.x`),三者的竖线是一条。
 *  ⑥ **控件圆角跟控件高度走**:`control / controlH.form` 落在 0.38–0.48 之间
 *     (34 高配 14 → 0.41)。改控件高度而不动圆角,按钮就会在"胶囊"和"方块"
 *     之间漂移。
 *  ⑦ **连续圆角只作用于 control / card / panel**(见下方 cornerSmoothing);
 *     pill 与正圆显式 `corner-shape: round`。
 */
export const radius = {
  /** 控件:按钮、输入框、搜索栏、分类 chip、缩略图 → 14 */
  control: 14,
  /** 卡片 / 行:记忆问题行、标准回答卡、知识库卡 → 16 */
  card: 16,
  /** 浮层:聊天页推荐面板(它是唯一真正浮起来的东西)、图片预览的图 → 20 */
  panel: 20,
  /** 全圆端:开关轨道、状态标、键帽、分类 pill */
  pill: 9999,
} as const

/**
 * ── 连续圆角(iOS squircle / corner smoothing)───────────────────────────────
 *
 * 半径回答"拐多大的弯",**平滑度**回答"这条弯怎么拐"。
 *
 * 普通 `border-radius` 是正圆的一段弧:弧与直边在切点处**曲率突变**,眼睛能读到
 * 那条"接缝";iOS 的连续圆角让曲率从直边一路渐变到顶点,整圈读作一条连续的线。
 * 这就是为什么同样 14px 的圆角,iOS 的按钮看起来"更整",而 web 上的容易显硬。
 *
 * 取 **0.6(60%)** —— 这是 iOS 的默认平滑度,Figma 的 corner smoothing 默认值
 * 也是 60%,出处就是苹果这套曲线。
 *
 * 实现走 CSS `corner-shape: superellipse(k)`(Chrome 139+;本扩展只跑在 Chrome 上,
 * 而且不支持的浏览器会**直接忽略这条声明退回普通圆角**,不存在降级风险)。
 * 换算:Chrome 的 `k = 1` 就是正圆(等价 `round`),`k = 2` 是它自己的 `squircle`
 * 关键字,所以
 *
 *     k = 1 + 平滑度 × 5/3      → 0 → 1(正圆),0.6 → 2(超椭圆)
 *
 * 再往上(0.8 → k≈2.3)圆角开始读作"被削过的方角",不再像圆角,故不取。
 *
 * ⚠️ 只给**中等圆角**用:卡片 15 / 控件 13 / 浮层 18。胶囊(`radius.pill`)与正圆
 * (`50%`)保持正圆 —— 它们的语义就是"全圆端",被抹成超椭圆反而像削角。
 */
export const cornerSmoothing = 0.6

/** 超椭圆参数 k —— 由平滑度单点推出,各处**不要**另写数字 */
export const cornerShapeK = 1 + cornerSmoothing * (5 / 3) // 0.6 → 2

/** `corner-shape` 的声明值(四处样式表共用这一个字符串) */
export const cornerShape = `superellipse(${Number(cornerShapeK.toFixed(3))})`

