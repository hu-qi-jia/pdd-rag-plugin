// ── 圆角(px)— 四档,每种用途一档,不许混用 ─────────────────────────────────
/**
 * v4.0 → v5.0 的关键变化:**列表重新有了圆角**。
 *
 * v4.0 把行做成通铺(理由:整页同一类条目,拆成块就成了碎片),v5.0 按第六十七轮
 * 设计稿改回**每行一张卡**。于是圆角从三档变四档,并且**卡档要比控件档大** ——
 * 大面积的容器配小圆角会显得"没倒角",小控件配大圆角会显得"太软"。
 *
 * 档位关系(由大到小):浮层 18 > 卡片 15 > 控件 13。相邻档差 2–5px,
 * 保证"哪个裹着哪个"一眼能读出来,又不至于像三种不同的语言。
 */
export const radius = {
  /** 控件:按钮、输入框、搜索栏、分类 chip → 13 */
  control: 13,
  /** 卡片 / 行:记忆问题行、标准回答卡、知识库卡 → 15 */
  card: 15,
  /** 浮层:聊天页推荐面板(它是唯一真正浮起来的东西)→ 18 */
  panel: 18,
  /** 全圆端:开关轨道、状态标、键帽、分类 pill */
  pill: 9999,
} as const

// ── 间距(px)────────────────────────────────────────────────────────────────
export const spacing = {
  xs: 4,
  sm: 6,
  md: 8,
  lg: 10,
  xl: 12,
  xxl: 16,
} as const

/**
 * 卡片列表的几何 —— v5.0 新增。
 *
 * v4.0 的行是**通铺**的(通到面板边缘,行自己带 16px 内边距),所以那时不需要
 * 这组常量。改成卡片之后多出两个硬性要求:
 *   - 卡片**不能贴到面板边缘** —— 贴边的圆角会被裁成直角,卡片就不成立了;
 *   - 卡片之间要有一道**空隙**,那是"两张卡"唯一的证据(通铺靠发丝线,卡片靠间隙)。
 */
export const listGap = {
  /** 卡片之间的空隙。取 sm(6):再大会明显少放一行,再小会被读成"一块底色" */
  card: spacing.sm,
  /** 列表容器左右内边距 —— 必须 ≥ radius.card,否则圆角视觉上仍会被边缘切平 */
  inset: spacing.xxl,
} as const

