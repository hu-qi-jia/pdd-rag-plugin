/**
 * 设计规范(Design Tokens)— 本扩展唯一视觉真源
 *
 * **v5.0「暖纸」**(第六十七轮 · 方向 D「柔雾米白」落地)
 *
 * 手感来自 iOS(填充式控件、胶囊开关、淡底选中、克制的缓动),
 * 但 v5.0 把底色从"纯白/纯黑"换成**暖纸/暖褐**,并把行从通铺改成卡片。
 *
 * ── 从 v4.0 继承下来、本版**没有**改的三条 ────────────────────────────────
 *  ① **不是全等宽**。等宽只留给数字(计数、时间戳、键帽、字母槽);中文正文走
 *     系统无衬线 —— 整屏等宽对中文其实只改变了标点,换来的是"冷"不是"极客"。
 *  ② **字号阶梯 17/15/13/12**,控件 34/28。密度让给可读性。
 *  ③ **动效只做回执不做表演**(见 `motion`)。这是全天候使用的高频工具。
 *
 * ── 本版改了两条 ─────────────────────────────────────────────────────────
 *  ④ **列表重新有圆角**。v4.0 把行做成通铺(v3.0 的"一堆盒子"矫枉过正),
 *     v5.0 按设计稿改回**每行一张卡**,圆角因此从三档变四档(见 `radius`)。
 *     连带新增 `listGap` —— 卡片必须离面板边缘有内缩,否则圆角被裁平。
 *  ⑤ **引入单一强调色**。v4.0 除 danger 外全无彩;v5.0 加赭陶一系四枚令牌,
 *     用法见 theme.ts 文件头。
 *
 * 任何页面/组件不得硬编码字号、圆角、间距、颜色,一律引用本文件与 theme.ts。
 */

