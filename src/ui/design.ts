// ── 列表行的骨架尺寸(记忆页 / 标准回答页共用)────────────────────────────────
/**
 * 两个列表页的行是**同一个骨架**(v3.0 第三版统一,见 docs/DESIGN.md §七-G):
 *
 * ```
 * [主行]   标题(问题) ........................ [行尾操作列]
 * [元信息] 时间 · 条数 · 剩余 …(统一字号颜色,`·` 分隔)
 * [内容]   引文块(回复)/ 灰色预览(答复)
 * ```
 *
 * 参照 Hacker News / GitHub issue 列表那条通行做法:**一行标题 + 一行元信息** ——
 * 凡是会变成第三行的东西,要么并进元信息行,要么收进行尾的操作列。
 * 这两页此前没有统一骨架,元素各自漂浮,是"看起来乱"的真正原因。
 */
export const listRow = {
  /** 主行标题的行高倍率 */
  titleLineHeight: 1.4,
  /** 元信息行的行高倍率(比标题更紧:它是附属信息) */
  metaLineHeight: 1.35,
  /**
   * 行尾操作列相对主行顶端的偏移。
   *
   * 为什么需要它:标题可以占 **1~2 行**,而操作钮固定 24px。若用 `align-items: center`,
   * 一行标题与两行标题的行会把钮放在不同的 y 上,跨行看就**不成一列**;
   * 若直接顶对齐,钮又会比第一行文字偏低。故固定为 `flex-start` + 这个偏移,
   * 把钮**光学居中**到第一行文字上 —— 于是无论标题占几行,动作列都落在同一个 y。
   * 由 `fontSize.body × titleLineHeight` 与 `controlH.inline` 推出,不写死。
   */
  opsOffsetY: Math.round((fontSize.body * 1.4 - controlH.inline) / 2),
} as const

