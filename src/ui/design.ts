// ── 材料(浮层的"质感"参数)─────────────────────────────────────────────────
/**
 * 浮层材料参数(v2.7.0 第四十九轮,用户"大胆一点,简约风格,类似 apple 的设计")。
 *
 * 这是本设计规范里唯一一处"非几何、非配色"的令牌:面板不再靠**一面实心底 + 一圈描边**
 * 与页面切分,而是靠**半透明底 + 背景模糊**成为一张"材料"。参数取 Apple 材料同款
 * (saturate 180% / blur 20px):模糊半径决定"看不看得见后面" ——
 * 小于 12px 时后面的文字仍可辨认,那就会退回用户反馈过的"面板怎么是半透明的";
 * 20px 下后面只剩色块,观感是一块实心的磨砂板。
 */
export const material = {
  /** 背景模糊半径(px)—— 低于 12 后面文字仍可辨认,不视为合格材料 */
  blurPx: 20,
  /** 背景饱和度提升 —— 让透过来的平台页底色不发灰 */
  saturate: '180%',
} as const

